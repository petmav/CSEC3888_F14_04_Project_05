#!/usr/bin/env python3
"""Recolour Rabby's hardcoded blues to Redbelly red.

Most of the UI takes its colours from the palette in
`src/constant/theme-colors.js`, which is edited by hand. Hundreds of styles
and SVG icons upstream hardcode Rabby's blues instead; this rewrites those
literals. Run it after merging a new Rabby release - it only touches exact
colour literals and is safe to re-run (a second run changes nothing).

Brand colours from redbelly.network: #FF4646 primary, #FF7373 light.

Usage: python scripts/redbelly-restyle.py   (from the repository root)
"""
import glob
import re
import sys

HEX = {
    # Rabby brand blues
    '4c65ff': 'FF4646',
    '7084ff': 'FF4646',
    '4d68ff': 'FF4646',
    '5f75ff': 'FF5A5A',
    '3e5bff': 'E63434',
    '8697ff': 'FF7373',
    'a5b2ff': 'FFA5A5',
    'b0bdff': 'FFB0B0',
    # light-mode tints
    'edf0ff': 'FFEDED',
    'eef1ff': 'FFF0F0',
    'eff1ff': 'FFF0F0',
    'dbe0ff': 'FFDBDB',
    'dee3fc': 'FCDEDE',
    'ecf3ff': 'FFF3F3',
    'ccd2ff': 'FFD2D2',
    'b8c1ff': 'FFC1C1',
    # dark-mode navies
    '232b4e': '3A1D22',
    '2a3770': '4A232A',
}
RGB = {
    (76, 101, 255): (255, 70, 70),
    (112, 132, 255): (255, 70, 70),
    (134, 151, 255): (255, 115, 115),
    (12, 15, 31): (11, 11, 13),
}

HEX_RE = re.compile(r'#(' + '|'.join(HEX) + r')\b', re.I)
RGB_RE = re.compile(r'(rgba?\(\s*)(\d+)(\s*,\s*)(\d+)(\s*,\s*)(\d+)')
EXTENSIONS = ('tsx', 'ts', 'less', 'css', 'svg', 'html')
SKIP = {'src/ui/style/cssvars.css'}  # generated by scripts/make-theme.js


def recolour(text):
    def hex_sub(m):
        new = HEX[m.group(1).lower()]
        return '#' + (new.lower() if m.group(1).islower() else new)

    def rgb_sub(m):
        key = (int(m.group(2)), int(m.group(4)), int(m.group(6)))
        if key not in RGB:
            return m.group(0)
        r, g, b = RGB[key]
        return f'{m.group(1)}{r}{m.group(3)}{g}{m.group(5)}{b}'

    text, a = HEX_RE.subn(hex_sub, text)
    text, b = RGB_RE.subn(rgb_sub, text)
    return text, a + b


def main():
    files = changes = 0
    for ext in EXTENSIONS:
        for path in glob.glob(f'src/ui/**/*.{ext}', recursive=True):
            if path.replace('\\', '/') in SKIP:
                continue
            raw = open(path, 'rb').read()
            try:
                text = raw.decode('utf8')
            except UnicodeDecodeError:
                continue
            new, n = recolour(text)
            if new != text:
                open(path, 'wb').write(new.encode('utf8'))
                files += 1
                changes += n
    print(f'{changes} colour literals changed in {files} files')
    return 0


if __name__ == '__main__':
    sys.exit(main())
